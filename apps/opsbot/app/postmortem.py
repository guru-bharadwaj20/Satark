"""/postmortem: draft a blameless postmortem from alerts, diagnoses and metrics."""

from __future__ import annotations

import logging
import re
import time
from collections import deque
from dataclasses import dataclass
from datetime import UTC, datetime

import httpx

from app.llm import LLMClient, LLMError

log = logging.getLogger("satark.opsbot.postmortem")

TEMPLATE = """# Postmortem: <title>

- **Status:** Draft (generated by opsbot, needs human review)
- **Date:** <date>
- **Severity:** <sev>

## Summary
## Impact
## Timeline (UTC)
## Root cause
## Detection
## Resolution
## What went well
## What went wrong
## Action items
| Action | Type (prevent/detect/mitigate) | Owner | Due |
|---|---|---|---|
## Lessons learned"""

SYSTEM = f"""You draft blameless postmortems for the Satark platform team.
Use ONLY the facts provided (alert timeline, opsbot diagnoses, notes). Where a fact is
unknown write "TBD" instead of inventing it. Blameless: describe systems and decisions,
never blame individuals. Keep it concise. Output Markdown following this template:

{TEMPLATE}"""


@dataclass(frozen=True)
class HistoryEntry:
    at: float
    alert: str
    namespace: str
    severity: str
    summary: str


class IncidentHistory:
    """Recent diagnoses kept in memory for postmortem drafts."""

    def __init__(self, maxlen: int = 100) -> None:
        self.entries: deque[HistoryEntry] = deque(maxlen=maxlen)

    def add(self, alert: str, namespace: str, severity: str, summary: str, at: float | None = None):
        self.entries.append(
            HistoryEntry(at or time.time(), alert, namespace, severity, summary[:1500])
        )

    def since(self, ts: float, alert: str | None = None) -> list[HistoryEntry]:
        return [e for e in self.entries if e.at >= ts and (not alert or e.alert == alert)]


def _fmt(ts: float) -> str:
    return datetime.fromtimestamp(ts, UTC).strftime("%Y-%m-%d %H:%M")


async def alert_timeline(
    client: httpx.AsyncClient, alertname: str | None, hours: int, now: float | None = None
) -> list[str]:
    """Firing intervals from the Prometheus ALERTS series."""
    end = now or time.time()
    start = end - hours * 3600
    sel = (
        f'ALERTS{{alertstate="firing"{"," if alertname else ""}'
        + (f'alertname="{alertname}"' if alertname else "")
        + "}"
    )
    r = await client.get(
        "/api/v1/query_range", params={"query": sel, "start": start, "end": end, "step": 60}
    )
    r.raise_for_status()
    out = []
    for s in r.json()["data"]["result"]:
        m = s["metric"]
        ts = [float(t) for t, _ in s["values"]]
        if not ts:
            continue
        # Split into intervals where there is a gap > 2 steps.
        begin = prev = ts[0]
        for t in ts[1:] + [None]:
            if t is None or t - prev > 120:
                where = m.get("namespace", "-") + "/" + (m.get("pod") or m.get("service") or "-")
                out.append(
                    f"{_fmt(begin)} -> {_fmt(prev)} {m.get('alertname')} "
                    f"[{m.get('severity', '?')}] {where}"
                )
                if t is not None:
                    begin = t
            if t is not None:
                prev = t
    return sorted(out)


_ALERT = re.compile(r"^[A-Z][A-Za-z0-9_:]{2,}$")
_HOURS = re.compile(r"^(\d{1,2})h$")


def parse_args(arg: str) -> tuple[str | None, int, str]:
    """'[AlertName] [Nh] [notes...]' -> (alert, hours 1..72, notes). Defaults: all, 6h."""
    tokens = arg.split()
    alert, hours = None, 6
    t0 = tokens[0] if tokens else ""
    # Alert names are CamelCase (KubePodCrashLooping); plain words start the notes.
    if _ALERT.match(t0) and sum(c.isupper() for c in t0) >= 2 and any(c.islower() for c in t0):
        alert = tokens.pop(0)
    if tokens and (m := _HOURS.match(tokens[0])):
        hours = int(m.group(1))
        tokens.pop(0)
    return alert, max(1, min(hours, 72)), " ".join(tokens)


class PostmortemGenerator:
    def __init__(self, llm: LLMClient, prometheus: httpx.AsyncClient, history: IncidentHistory):
        self.llm, self.prom, self.history = llm, prometheus, history

    async def draft(self, arg: str, now: float | None = None) -> tuple[str, int]:
        """arg: '[AlertName] [Nh] [free-text notes]' (defaults: all alerts, 6h)."""
        alert, hours, notes = parse_args(arg)
        now = now or time.time()
        try:
            timeline = await alert_timeline(self.prom, alert, hours, now)
        except (httpx.HTTPError, KeyError, ValueError) as exc:
            timeline = [f"(Prometheus unavailable: {type(exc).__name__})"]
        diag = self.history.since(now - hours * 3600, alert)
        facts = [
            f"Window: last {hours}h ending {_fmt(now)} UTC. Alert filter: {alert or 'all'}.",
            "",
            "ALERT TIMELINE:",
            *(timeline or ["no firing alerts found"]),
            "",
            "OPSBOT DIAGNOSES:",
            *(
                [
                    f"{_fmt(e.at)} {e.alert} ({e.namespace}, {e.severity}):\n{e.summary}"
                    for e in diag
                ]
                or ["none recorded"]
            ),
            "",
            f"OPERATOR NOTES: {notes or 'none'}",
        ]
        try:
            reply = await self.llm.chat(SYSTEM, "\n".join(facts), max_tokens=1500)
        except LLMError as exc:
            log.warning("postmortem llm failed: %s", exc)
            skeleton = (
                TEMPLATE.replace("<title>", alert or "incident")
                .replace("<date>", _fmt(now)[:10])
                .replace("<sev>", "TBD")
            )
            return skeleton + "\n\n<!-- facts -->\n" + "\n".join(facts), 0
        return reply.text.strip(), reply.total_tokens
